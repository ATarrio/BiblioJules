"""Dump the server's table/column layout for the mobile app's schema check.

The phone keeps its own copy of the schema (``mobile/lib/src/local/schema.dart``)
so it can work with no server at all, and that copy is only safe if it stays
identical to the server's. This writes out what SQLAlchemy believes — the truth
the server actually runs on — and
``mobile/test/schema_parity_test.dart`` fails the moment the two drift apart.

Run it after touching anything under ``app/models/``::

    python dump_schema.py

The result is committed, so the mobile test suite needs no Python to run.
"""

from __future__ import annotations

import json
from pathlib import Path

from app import models  # noqa: F401  (importing registers every table)
from app.database import Base

TARGET = Path(__file__).resolve().parent / "mobile" / "test" / "fixtures" / "server_schema.json"


def main() -> None:
    tables = {
        table.name: [column.name for column in table.columns]
        for table in Base.metadata.sorted_tables
    }
    payload = {
        "//": "Generated by dump_schema.py — do not edit by hand.",
        "tables": tables,
    }
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(
        json.dumps(payload, indent=2, sort_keys=True, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    print(f"wrote {TARGET.relative_to(TARGET.parents[3])} ({len(tables)} tables)")


if __name__ == "__main__":
    main()
